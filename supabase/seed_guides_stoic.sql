> *"She studies why newborn goats die in spring, and turned the answers into voice messages herders without internet can use."* Tag: **the goat-survival counter from Uvs**.

## 4. Tuvshuu, Class 10–11, Erdenet: "I like business"

**Before (2/5):** business club member, football, weekend cashier at the family shop.

- **Narrow:** at the shop he read the credit notebook (neighbours buying now, paying later) → *how informal shop credit works in Erdenet*.
