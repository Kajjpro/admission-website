- **Edge (people + discipline):** Saturday script sessions for Class 5 pupils, grown from 4 to 62, later joined by a soum school by video.
- **Sort:** spike = app, fair entries, NLP course · edge = Saturday sessions, soum partnership · texture = volleyball, piano, looking after cousins · dropped = MUN, newspaper, English club (one year each, no growth).

