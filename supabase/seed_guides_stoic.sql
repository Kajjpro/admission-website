Letters are the only part of your file written by people who watched you work for months.

| Letter | What it shows |
| --- | --- |
| **Counsellor** (+ school profile) | You against your whole class; explains your school |
| **Teacher 1** (math or science) | How you think in a STEM subject, seen up close |
| **Teacher 2** (humanities or language) | How you write, argue and discuss |
