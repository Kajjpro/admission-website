A claim, a moment that proves it, and a comparison that shows how rare it is.

**The evidence ladder:**

1. Adjective: *"Khaliun is responsible."*
2. Claim: *"She is a natural leader of younger pupils."*
3. Incident: *"Every Saturday since autumn she has taught script to Class 5 pupils. I visited twice without warning."*
4. Incident + comparison: *"…both times a struggling pupil left able to read a new word. In sixteen years, she is one of very few students who teaches what she loves."*

