## What the colleges themselves say

- **Harvard.** The U.S. Supreme Court's 2023 opinion in *SFFA v. Harvard* describes readers rating each applicant from 1 (best) to 6. A 1 in extracurriculars means "truly unusual achievement." The top rating rewards **how far you went**, not how many clubs you joined.
- **Yale.** Its "What Yale Looks For" page asks two questions: who will make the most of Yale's resources, and who will contribute most to its community? Depth shows how you used what your school offered; an edge shows what you'd give a community.
- **MIT.** Admissions director Chris Peterson (interviewed by Art of Problem Solving): first MIT checks that you can do the work. After that, "we're building a team," and each decision depends on everyone else in the pool. **Be the person the team is missing.**

## Three things the spike idea does not mean

1. **It does not replace grades.** Every selective school first checks that you can handle the work.
2. **It is not the only winning shape.** Three activities that all answer one question form a *theme*, and that works too. What doesn't work is *scatter*: many activities pointing nowhere.
3. **It is read in context.** Readers ask what you did with what you had. A spike built at a soum school with no lab looks different from one built at an international school in Ulaanbaatar, and both can be strong.

## What a spike is not (yet)

| Looks like a spike | Why it isn't | Fix |
| --- | --- | --- |
| A title ("President, English Club") | Says what you were called, not what you did | Add an output and a number |
| A price tag (an expensive program) | Anyone who pays can attend | Choose things that select you |
| A category ("computer science") | Thousands of applicants say the same word | Narrow it to a specific problem |
| A hobby with no thread (piano, for CS) | Deep, but pointing away from your studies | Keep it as texture |
| A one-off (one summer camp) | No time, no progression | Continue it for a year and let your role grow |
| A hook (recruited athlete, legacy) | An institutional reason, not a spike | Most Mongolian applicants have no hook; build the spike |

