## 2. Bataa, Class 11, Darkhan: deep but private

**Before (5/5):** math olympiad 4 yrs × 8 hrs/week, a 60-problem geometry set, national bronze. Hundreds of applicants have a medal; the question is what his skill does for anyone else.

