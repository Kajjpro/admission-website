$md$A **double edge** is a second angle that carries your spike to other people, into another medium, or across into a second field. It turns "good at X" into "good at X, and here is where X goes."

The term comes from the consulting firm ElevatEd. The idea, depth plus impact beyond yourself, matches Yale's second question: what will you contribute to a community?

## Three kinds of edge

| Kind | What it means | Examples |
| --- | --- | --- |
| **People edge** | Your spike serves someone who lacks access to it | Robotics → Saturday robotics workshops at a children's centre in Songinokhairkhan. Chemistry olympiad → a free problem-solving circle for Class 8 girls in Darkhan. |
| **Medium edge** | Your spike moves into a new form | Olympiad math → Mongolian-language video explainers. Veterinary biology → a picture book on newborn-goat care for herding families. |
| **Discipline edge** | Your spike meets a second field that explains it better | Computer science + linguistics → tools for the traditional script. Physics + music → measuring overtones in khöömei throat singing. |

Many strong edges combine two kinds. Bataa's geometry videos are a medium edge (video) and a people edge (soum students) at once.

## The Bridge Test

Write **one sentence** that uses your spike to explain your edge. If it needs "and also," there is no bridge.

| Fails | Passes |
| --- | --- |
| "She does robotics and also volunteers at a shelter." | "She built competition robots, then built a workshop so children at a shelter could build them too." |
| "She codes and also speaks three languages." | "She writes code that reads the traditional script, because her cousins can't." |
| "He likes biology and also draws." | "He studies how goats survive winter, and turned what he learned into a picture book herders actually use." |

The failing and passing sentences list the same activities. What changes is the **because** or the **so that** joining them.

## Bridges that pass

- "She trains for chemistry olympiads, and runs the circle she wished had existed when she was the only girl in the room."
- "He builds cheap air sensors, and puts the readings on a map parents check before school."
- "She writes fiction, and teaches children in hospital to write their own endings."
- "He studies how mining revenue moves through the national budget, and explains it in ten-minute episodes for students."
- "She studies sound waves, and measures what lets a throat singer produce two notes at once."
- "He writes software, and built the booking system that ended the 6 a.m. line at his soum clinic."
- "She studies how teenagers handle stress, and trained 12 classmates to run a listening room at lunch."

## Repairing bridges that fail

| Fails | Repaired |
| --- | --- |
| "He does robotics and also volunteers at a kindergarten." | "He builds robots, and teaches kindergarten children to program a simple one." |
| "She loves biology and also paints." | "She studies plant cells, and paints the illustrations for a biology handout in Mongolian." |
| "She studies economics and also started a charity." | "She studies household budgets, so her charity gives families a monthly budget plan, not only food." |
| "He likes history and also makes videos." | "He researches how Ulaanbaatar's street names changed, and turns each change into a one-minute video." |
| "He's in the math olympiad and also plays basketball." | Don't force it. Basketball is texture. Not every activity needs a bridge. |

> **The repair rule:** look for the *because* or the *so that*. If it exists, write it down. If not, build the link for real (teach, make, measure) or leave the activity as texture. **Never write a bridge that isn't true.**

## Edge or texture?

An edge is joined to your spike. **Texture** is everything else that shows the rest of you: volleyball, the morin khuur, caring for younger siblings, a summer job. Texture needs no bridge, and you should keep it. A strong file usually has spike, edge **and** texture.

Distance helps only while the bridge still holds: physics and music, bridged by khöömei acoustics, is memorable; robotics and piano with no bridge is just two lists.

## Three questions to find your edge

1. Who doesn't have access to what I know? → **people edge**
2. What form could carry it further (video, writing, an app, a book, a performance)? → **medium edge**
3. Which second subject would explain my spike better? → **discipline edge**
