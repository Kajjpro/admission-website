| Part | Example |
| --- | --- |
| Context | "I have taught Bataa geometry for two years and coached him for three olympiad seasons." |
| Incident ×2–3 | "In March he found a shorter proof of a problem I have taught for nine years." |
| Comparison | "Of roughly 400 students, he is one of two I would call genuinely original." |
| Endorsement | "I recommend him without reservation, the strongest recommendation I give." |

