$md$## The short version

**No activity is good or bad because of its name.** "President" can be empty and "family shop" can be one of the strongest lines in a file. Readers ask four things about every activity:

1. **Depth over time:** how long, how often, and did you get better?
2. **Role and initiative:** what exists or works differently because of you?
3. **Reach, relative to your context:** how far beyond you did it go, given the opportunities you had?
4. **Verifiable recognition:** can someone outside your family confirm it?

Then they ask one bigger question about the whole list: **what is this student remembered for?** That is your spike.

## Why the spike matters so much

A selective college builds a class the way a coach builds a team. Picture a Naadam team: thirty people who are "okay" at wrestling, archery and horse racing lose to a team with one wrestler who can win, one archer who can win and one jockey who can win.

Once your grades clear the bar, colleges reward students who are **unusually strong at something specific**:

- In Harvard's reading process (described in the Supreme Court's 2023 SFFA opinion), a top extracurricular rating means "truly unusual achievement". That rewards how far you went, not how many clubs you joined.
- Yale asks who will make the most of its resources and who will contribute most to its community.
- MIT's admissions director describes it as "building a team": be the strength the team is missing.

A file with ten shallow activities leaves a reader remembering nothing. A file with one deep spike, a second angle that carries it to other people (the **double edge**), and an honest picture of the rest of your life (**texture**) is remembered and trusted.

> A spike sits on top of strong academics, never instead of them.

## Good: what readers reward

| Signal | Looks like |
| --- | --- |
| Years of commitment | Four years of debate, from first-time speaker to coaching new members |
| Something you built | No title, but you designed the tutoring schedule that now runs every week |
| Progression | School round → aimag round → national bronze |
| Real output | A problem set, an app, a survey report, a dataset, a film |
| Reach beyond you | Two nearby schools copied your physics study group |
| Selection | Picked by audition, chosen for a team, invited by a partner |
| Family responsibility | 15 hours a week at the family shop for three years, or leading spring birthing season for the herd |
| An academic thread | Chemistry olympiad, applying for chemistry |

Family work, herding, caring for siblings and paid jobs **count as full activities**. The Common App even has a Family Responsibilities category. Never leave them off because they feel ordinary.

## Bad: what readers discount (or distrust)

| Activity | Why it's weak | Do this instead |
| --- | --- | --- |
| Pay-to-attend programs | A famous university's name doesn't make a program selective. Readers know which ones admit anyone who pays. | Free or funded programs with real selection, or meaningful work at home |
| Pay-to-publish "research" | Journals that charge students to publish have no real review, and readers recognize them. | Real research with a teacher or mentor, even unpublished; describe what you found |
| Empty founder titles | "Founder and CEO" of something with a logo and no results is extremely common. | Build inside an existing club first; results matter more than titles |
| Vanity numbers | Followers and views show attention, not impact. | Describe what the account or app actually does for its users |
| Last-minute activities | Starting four things in Grade 12 looks manufactured. | Strengthen what you already do |
| Awards anyone can win | Entry-fee contests with many "winners" show no selectivity. | Competitions where you can say how many entered and how few placed |
| One-off service | A single visit to a children's centre isn't an edge. Thirty Saturdays are. | Commit, then grow your role |
| Inflated claims | Counselors and teachers can confirm details, and one false claim damages everything else. | Exact, honest numbers. A true Level 3 beats a false Level 4. |

## The five levels

Instead of ranking activity types, place each activity on a level:

1. **Present:** you take part occasionally. Doesn't hurt; carries little weight.
2. **Committed:** you show up reliably for years and your skill or responsibility grows.
3. **Leading:** you own something others depend on.
4. **Distinguished:** your work reaches beyond your school (city or aimag recognition, a selective team, people outside your circle use it).
5. **Rare:** very few students anywhere reach it (national medal, international team).

Strong applications usually have **one or two activities at the top of their range** and several solid ones below, not ten at the highest level. You don't need to fill all ten Common App spaces.

## Spike, theme or scatter?

- **Spike (works):** one area, very deep. *"The Mongolian-script programmer."*
- **Theme (works):** two or three activities answering one question. *"Why do girls in Darkhan leave science after Class 9?"*
- **Scatter (grow out of it):** robotics, debate, piano, volleyball, MUN, chess, all pointing nowhere.

