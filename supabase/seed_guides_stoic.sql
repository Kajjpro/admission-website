## 1. Khaliun, Class 10, Ulaanbaatar: from "CS" to a script app

**Before (2/5):** nine activities, ~19 hrs/week: robotics, coding club, MUN, volleyball, piano, newspaper, English club, online Python, occasional volunteering.

